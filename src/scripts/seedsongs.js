const getContentType = (filePath) => {
  const ext = path.extname(filePath).toLowerCase();
  if (ext === '.m4a') return 'audio/mp4';
  if (ext === '.wav') return 'audio/wav';
  return 'audio/mpeg'; // .mp3 default
};

const uploadToS3 = async (songId, filePath) => {
  const filename = path.basename(filePath);
  const s3Key = `songs/${songId}/${filename}`;
  console.log(`  ☁️  Uploading "${filename}" → s3://${BUCKET}/${s3Key}`);

  const fileStream = fs.createReadStream(filePath);
  fileStream.on('error', (err) => { throw new Error(`Cannot read file: ${err.message}`); });

  await s3.upload({
    Bucket: BUCKET,
    Key: s3Key,
    Body: fileStream,
    ContentType: getContentType(filePath),
  }).promise();

  const songURL = `https://${BUCKET}.s3.${process.env.AWS_REGION}.amazonaws.com/${s3Key}`;
  console.log(`  ✅ Uploaded → ${songURL}`);
  return { s3Key, songURL };
};

const writeToDynamoDB = async (song, s3Key, songURL) => {
  const item = {
    PK: `SONG#${song.songId}`,
    SK: 'META',
    song_ID: song.songId,
    name: song.name,
    artist: song.artist,
    album: song.album,
    description: song.description,
    moods: song.moods,         // already [{ S: '...' }] format
    s3Key,
    songURL,
    createdAt: new Date().toISOString(),
  };

  await dynamoDB.put({
    TableName: TABLE,
    Item: item,
  }).promise();

  console.log(`  ✅ DynamoDB record saved for "${song.name}"`);
};

// ─── MAIN ─────────────────────────────────────────────────────────────────────

const seed = async () => {
  if (!BUCKET) {
    console.error('❌  S3_BUCKET is not set in your .env. Aborting.');
    process.exit(1);
  }
  console.log(`\n🚀  Seeding ${songs.length} songs into "${TABLE}" ...\n`);

  for (const song of songs) {
    console.log(`▶  "${song.name}" — ${song.artist}`);
    if (!fs.existsSync(song.filePath)) {
      console.warn(`  ⚠️  File not found: ${song.filePath} — skipping.\n`);
      continue;
    }
    try {
      const { s3Key, songURL } = await uploadToS3(song.songId, song.filePath);
      await writeToDynamoDB(song, s3Key, songURL);
      console.log(`  🎵  Done\n`);
    } catch (err) {
      console.error(`  ❌  Error processing "${song.name}": ${err.message}\n`);
    }
  }

  console.log('✅  Seeding complete.');
};

seed();